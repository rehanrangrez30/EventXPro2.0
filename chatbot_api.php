<?php
/**
 * EventX Pro - Chatbot API
 *
 * Dependency-free, rule-based assistant (no external AI API — this keeps
 * the project fully offline/XAMPP-compatible per the project's asset
 * policy). Matches keywords against common questions and, where useful,
 * pulls live answers from the database (e.g. "how many events").
 */
require_once __DIR__ . '/config/config.php';
require_once __DIR__ . '/config/db.php';
require_once __DIR__ . '/includes/functions.php';

header('Content-Type: application/json');

$message = strtolower(trim($_POST['message'] ?? ''));

if ($message === '') {
    echo json_encode(['reply' => "I didn't catch that — could you rephrase your question?"]);
    exit;
}

function contains(string $haystack, array $needles): bool
{
    foreach ($needles as $needle) {
        if (str_contains($haystack, $needle)) {
            return true;
        }
    }
    return false;
}

$reply = null;

if (contains($message, ['register', 'registration', 'sign up', 'how to join'])) {
    $reply = 'To register for an event: browse Events, open the one you like, and click "Register Now." '
           . 'You need a student account and must register before the deadline shown on the event page.';
} elseif (contains($message, ['cancel'])) {
    $reply = 'You can cancel a registration any time before the event by opening it from '
           . '"My Registrations" and clicking "Cancel Registration."';
} elseif (contains($message, ['certificate'])) {
    $reply = 'Certificates are generated by the organizer after an event is marked complete and your '
           . 'attendance is confirmed. Download yours from the "Certificates" page, and verify any '
           . 'certificate at certificate_verify.php using its verification code.';
} elseif (contains($message, ['password', 'forgot', 'login', 'log in', 'sign in'])) {
    $reply = 'Having trouble logging in? Use the "Forgot password?" link on the login page to reset it, '
           . 'or double-check your registered email address.';
} elseif (contains($message, ['deadline'])) {
    $stmt = $pdo->query(
        "SELECT title, registration_deadline FROM events
         WHERE status = 'published' AND registration_deadline >= NOW()
         ORDER BY registration_deadline ASC LIMIT 3"
    );
    $rows = $stmt->fetchAll();
    if ($rows) {
        $lines = array_map(
            fn ($r) => '• ' . $r['title'] . ' — closes ' . date('d M Y, h:i A', strtotime($r['registration_deadline'])),
            $rows
        );
        $reply = "Here are the nearest registration deadlines:\n" . implode("\n", $lines);
    } else {
        $reply = 'There are no upcoming registration deadlines right now — check the Events page for what\'s next.';
    }
} elseif (contains($message, ['how many event', 'upcoming event', 'events available', 'what event'])) {
    $count = (int) $pdo->query("SELECT COUNT(*) FROM events WHERE status = 'published' AND event_date >= CURDATE()")->fetchColumn();
    $reply = $count > 0
        ? "There are currently $count upcoming published events. Check the Events page to browse them all."
        : 'There are no upcoming published events right now — check back soon!';
} elseif (contains($message, ['volunteer'])) {
    $reply = 'Volunteers are assigned to events and tasks by the administrator. Once assigned, you can see '
           . 'your events and tasks from your Volunteer Dashboard.';
} elseif (contains($message, ['faculty', 'supervis'])) {
    $reply = 'Faculty members are assigned to specific events by the administrator for coordination, '
           . 'mentoring, or evaluation. Assigned events appear on your Faculty Dashboard.';
} elseif (contains($message, ['contact', 'support', 'help', 'email'])) {
    $reply = 'You can reach us through the Contact page, or email the address listed in the site footer.';
} elseif (contains($message, ['hi', 'hello', 'hey'])) {
    $reply = 'Hello! I can help with event registration, deadlines, certificates, and login questions. What do you need?';
} elseif (contains($message, ['thank'])) {
    $reply = "You're welcome! Let me know if there's anything else.";
} else {
    $reply = "I'm not sure about that one yet. Try asking about event registration, deadlines, certificates, "
           . 'or logging in — or visit the Contact page for direct help.';
}

echo json_encode(['reply' => $reply]);
